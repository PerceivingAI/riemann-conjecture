import argparse,copy,hashlib,json,os,shutil,subprocess,sys,tempfile,time
from fractions import Fraction as Q
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
REL=HERE.relative_to(ROOT).as_posix()

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def load(path):return json.loads(path.read_text(encoding='utf-8'))
def require(ok,message):
    if not ok:raise ValueError(message)
def write_new(path,value):
    with path.open('x',encoding='utf-8',newline='\n') as handle:handle.write(json.dumps(value,sort_keys=True,indent=2)+'\n')
def confined(base,name):
    require(isinstance(name,str) and name and '\\' not in name and ':' not in name,'invalid portable path')
    parts=name.split('/')
    require(not name.startswith('/') and all(p not in ('','.','..') for p in parts),'unsafe path components')
    result=(base/name).resolve();require(result.is_relative_to(base.resolve()),'path escape');return result

def run(root,script,args):
    command=[sys.executable,'-B',str(root/REL/script),*map(str,args)]
    env=os.environ.copy();env['PYTHONDONTWRITEBYTECODE']='1';env.pop('PYTHONPATH',None)
    for key in ('OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','MKL_NUM_THREADS','NUMEXPR_NUM_THREADS'):env[key]='1'
    started=time.perf_counter();process=subprocess.run(command,cwd=root,env=env,capture_output=True,text=True)
    return {'argv':command,'exit_code':process.returncode,'elapsed_seconds':time.perf_counter()-started,'stdout':process.stdout,'stderr':process.stderr}

def countercases():
    folder=HERE/'data'/'negative-controls-v1-cases';folder.mkdir(exist_ok=False)
    records=[]
    def case(name,source_name,consumer,input_name,mutate,reason,reference=False):
        source=copy.deepcopy(load(HERE/'data'/source_name));mutate(source)
        source_path=folder/(name+'.json');out=folder/(name+'-audit.json');write_new(source_path,source)
        args=['--inputs',HERE/input_name,'--source',source_path,'--output',out]
        if reference:args+=['--reference-audit',HERE/'data/supported-reference-audit-v1.json']
        receipt=run(ROOT,consumer,args)
        try:result=json.loads(receipt['stdout'])
        except json.JSONDecodeError:result={}
        require(receipt['exit_code']==2 and result.get('status') in ('REJECT','REJECTED') and reason in result.get('error','') and not out.exists(),'countercase did not reach its mathematical rejection: '+name+' '+json.dumps(receipt))
        records.append({'name':name,'mutated_source':source_path.relative_to(HERE).as_posix(),'mutated_source_sha256':digest(source_path),'expected_rejection_seam':reason,'rejection':result,'pass_output_created':out.exists(),'receipt':receipt})
    def zero_coefficient5(s):s['active_terms'][-1]['coefficient']={'lower':'0','upper':'0'}
    def double_coefficient4(s):
        x=s['active_terms'][2]['coefficient'];s['active_terms'][2]['coefficient']={k:str(2*Q(v)) for k,v in x.items()}
    def zero_transfer_charge(s):s['support_transfer']['coefficient5']={'lower':'0','upper':'0'}
    def zero_leakage(s):s['N_policy_trials'][-1]['leakage']={'lower':'0','upper':'0'}
    def zero_physical_inverse(s):s['inverse_weight']['kappa']={'lower':'0','upper':'0'}
    def omit_polar(s):s['kernel_coefficients'][0]='0'
    def omit_infinite_weight(s):s['inverse_weight_step_uppers'][-1]='0'
    def omit_mixed_squares(s):
        old=s['matrices']['P_squared'][0][0];rows=s['prime5_mixed_square_constant_mode']
        s['matrices']['P_squared'][0][0]={'lower':str(Q(old['lower'])-sum((Q(r['value']['upper']) for r in rows),Q(0))),'upper':str(Q(old['upper'])-sum((Q(r['value']['lower']) for r in rows),Q(0)))}
    def symmetrize_vp(s):
        old=copy.deepcopy(s['matrices']['VP'])
        for i in range(4):
            for j in range(4):s['matrices']['VP'][i][j]={k:str((Q(old[i][j][k])+Q(old[j][i][k]))/2) for k in ('lower','upper')}
        s['matrices']['PV']=copy.deepcopy(s['matrices']['VP'])
    common=('supported-reference-source-v1.json','verify-reference-v2.py','qualification-inputs-v3.json')
    for name,mutation,reason in [('omit-active-prime5',zero_coefficient5,'arithmetic coefficient'),('wrong-von-mangoldt4',double_coefficient4,'arithmetic coefficient'),('unpaid-supported-prime5',zero_transfer_charge,'supported transfer coefficient5'),('unpaid-complete-leakage',zero_leakage,'leakage at N='),('unpaid-physical-inverse',zero_physical_inverse,'inverse kappa')]:case(name,*common,mutation,reason)
    target=('target-declaration-source-v1.json','verify-target-declaration-v1.py','parameter-inputs-v1.json')
    case('omit-canonical-polar-coefficient',*target,omit_polar,'complete formal kernel coefficients',True)
    case('discard-frequency-infinity',*target,omit_infinite_weight,'inverse weight at ',True)
    topology=('topology-source-v1.json','verify-prime-five-topology-v1.py','topology-inputs-v1.json')
    case('discard-prime5-mixed-squares',*topology,omit_mixed_squares,'P_squared[0,0]')
    case('symmetrize-ordered-VP',*topology,symmetrize_vp,'VP[')
    return {'format':'t081-qualification-negative-controls-v1','status':'PASS','cases':records,'substantive_cases_passed':len(records),'scope':'actual native analytic rejection seams; not expected exit alone','full_target_matrix_or_sign_run':False,'production_admission':False}

def replay(capture_path):
    capture=load(capture_path);require(capture['format']=='t081-captured-source-inputs-v1','capture format')
    require(capture['support']=='81/100' and capture['production_admission'] is False,'capture scope')
    members=capture['members'];require(isinstance(members,list) and members,'empty capture')
    names=[m['project_path'] for m in members];require(len(names)==len(set(names)),'duplicate capture destination')
    receipts=[]
    with tempfile.TemporaryDirectory(prefix='t081-qualification-replay-') as temporary:
        root=Path(temporary);temporary_path=str(root);bundle=root/REL
        for member in members:
            origin=confined(HERE,member['captured_path']);target=confined(root,member['project_path'])
            require(digest(origin)==member['sha256'] and origin.stat().st_size==member['size'],'capture member changed')
            target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(origin,target)
        require(digest(root/REL/Path(__file__).name)==digest(Path(__file__)),'driver differs from captured version')
        def check(name,script,args,expected,output):
            receipt=run(root,script,args);require(receipt['exit_code']==0 and output.is_file(),'captured calculation failed: '+name+' '+json.dumps(receipt))
            fresh_hash=digest(output);expected_hash=digest(bundle/expected)
            require(fresh_hash==expected_hash,'captured calculation is not byte-identical: '+name)
            receipt.update({'check':name,'expected_project_path':REL+'/'+expected,'expected_sha256':expected_hash,'reproduced_sha256':fresh_hash,'byte_identical':True});receipts.append(receipt)
        data=bundle/'data'
        global_source=data/'reproduced-global-source.json';global_audit=data/'reproduced-global-audit.json'
        supported_source=data/'reproduced-supported-source.json';supported_audit=data/'reproduced-supported-audit.json'
        declaration=data/'reproduced-target-declaration.json';declaration_audit=data/'reproduced-target-audit.json'
        topology=data/'reproduced-topology-source.json';topology_audit=data/'reproduced-topology-audit.json'
        check('fresh-global-source','qualify-reference-v1.py',['--inputs',bundle/'qualification-inputs-v2.json','--output',global_source],'data/reference-source-v2.json',global_source)
        check('fresh-global-native-audit','verify-reference-v1.py',['--inputs',bundle/'qualification-inputs-v2.json','--source',global_source,'--output',global_audit],'data/reference-audit-v2.json',global_audit)
        check('supported-reference-source','qualify-reference-v2.py',['--inputs',bundle/'qualification-inputs-v3.json','--output',supported_source],'data/supported-reference-source-v1.json',supported_source)
        check('supported-reference-native-audit','verify-reference-v2.py',['--inputs',bundle/'qualification-inputs-v3.json','--source',supported_source,'--output',supported_audit],'data/supported-reference-audit-v1.json',supported_audit)
        check('target-declaration','declare-target-v1.py',['--inputs',bundle/'parameter-inputs-v1.json','--reference-audit',supported_audit,'--output',declaration],'data/target-declaration-source-v1.json',declaration)
        check('target-declaration-native-audit','verify-target-declaration-v1.py',['--inputs',bundle/'parameter-inputs-v1.json','--source',declaration,'--reference-audit',supported_audit,'--output',declaration_audit],'data/target-declaration-audit-v1.json',declaration_audit)
        check('four-mode-topology-source','qualify-prime-five-topology-v1.py',['--inputs',bundle/'topology-inputs-v1.json','--output',topology],'data/topology-source-v1.json',topology)
        check('four-mode-topology-native-audit','verify-prime-five-topology-v1.py',['--inputs',bundle/'topology-inputs-v1.json','--source',topology,'--output',topology_audit],'data/topology-audit-v1.json',topology_audit)
    require(not Path(temporary_path).exists(),'owned replay tree not removed')
    return {'format':'t081-qualification-captured-replay-v1','status':'PASS','capture_description_sha256':digest(capture_path),'captured_destinations':len(members),'checks':receipts,'byte_identical_calculations':len(receipts),'owned_temporary_tree':temporary_path,'owned_temporary_tree_removed':True,'full_target_matrix_or_sign_run':False,'production_admission':False,'shared_premise':'recorded host Python/FLINT runtime; captured project source and input bytes, not an OS sandbox or independent arithmetic library'}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--mode',choices=('negative','replay'),required=True);parser.add_argument('--capture',type=Path);parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
